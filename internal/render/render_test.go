// R-UCI-5: running the script twice gives the same result as running it
// once. A fake uci keeps the configuration in a file.
func TestUCIScriptIdempotent(t *testing.T) {
	sh, err := exec.LookPath("sh")
	if err != nil {
		t.Skip("no sh")
	}
	dir := t.TempDir()
	state := filepath.Join(dir, "state")
	// The fake uci stores "section.option=value" lines. Deleting
	// "@type[0]" removes the first section of that type.
	fakeUCI := `#!/bin/sh
state=` + state + `
touch "$state"
[ "$1" = -q ] && shift
case "$1" in
delete)
	sec=${2#network.}
	case "$sec" in
	@*)
		type=${sec#@}; type=${type%\[0\]}
		sec=$(grep "^[^.]*=$type\$" "$state" | head -n 1 | cut -d= -f1)
		[ -n "$sec" ] || exit 1
		;;
	esac
	grep -q "^$sec[.=]" "$state" || exit 1
	grep -v "^$sec[.=]" "$state" > "$state.new" || true
	mv "$state.new" "$state"
	;;
set|add_list) echo "${2#network.}" >> "$state" ;;
commit) ;;
*) exit 2 ;;
esac
`
	writeFile(t, filepath.Join(dir, "uci"), fakeUCI, 0o755)
	script := strings.Replace(render(t, "uci-script", testConfig()),
		"/etc/init.d/network reload", "true", 1)
	writeFile(t, filepath.Join(dir, "km.sh"), script, 0o755)

	// Stale configuration that the script must replace.
	writeFile(t, state, "wg_home=interface\nwg_home.mtu='1'\nwg_home_old=wireguard_wg_home\nwg_home_old.description='old'\nlan=interface\n", 0o644)

	run := func() string {
		cmd := exec.Command(sh, filepath.Join(dir, "km.sh"))
		cmd.Env = append(cmd.Environ(), "PATH="+dir+":/usr/bin:/bin")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("script failed: %v\n%s", err, out)
		}
		return readFile(t, state)
	}
	first := run()
	if strings.Contains(first, "old") || strings.Contains(first, "mtu='1'") {
		t.Errorf("stale configuration was not removed:\n%s", first)
	}
	if !strings.HasPrefix(first, "lan=interface\n") {
		t.Errorf("other configuration was removed:\n%s", first)
	}
	if second := run(); second != first {
		t.Errorf("second run differs:\nfirst:\n%s\nsecond:\n%s", first, second)
	}
}

// R-UCI-2
func TestQuote(t *testing.T) {
	for in, want := range map[string]string{
		"plain":     "'plain'",
		"":          "''",
		"it's":      `'it'\''s'`,
		"$(rm -rf)": "'$(rm -rf)'",
	} {
		if got := quote(in); got != want {
			t.Errorf("quote(%q) = %s, want %s", in, got, want)
		}
	}
}

// R-UCI-2: quoted values are safe in sh.
func TestQuoteInShell(t *testing.T) {
	sh, err := exec.LookPath("sh")
	if err != nil {
		t.Skip("no sh")
	}
	in := `a'b"c $HOME $(false) ` + "`x`\\"
	out, err := exec.Command(sh, "-c", "printf %s "+quote(in)).Output()
	if err != nil || string(out) != in {
		t.Errorf("sh printed %q, %v; want %q", out, err, in)
	}
}

