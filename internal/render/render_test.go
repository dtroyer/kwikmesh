// R-UCI-1: two peers whose section names collide are an error rather than
// one silently replacing the other.
func TestUCISectionCollision(t *testing.T) {
	cfg := testConfig()
	cfg.Peers[0].Name = "lap-top"
	cfg.Peers[1].Name = "lap.top"
	for _, format := range []string{"uci", "uci-script"} {
		f, _ := Lookup(format)
		_, err := f.Render(cfg)
		if err == nil || !strings.Contains(err.Error(), `both map to UCI section "wg_home_lap_top"`) {
			t.Errorf("%s: error = %v, want a collision", format, err)
		}
	}
}
