// internal/render/uci.go - OpenWRT uci and uci-script output formats

package render

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"

	"kwikmesh/internal/network"
)

type uciOption struct {
	list  bool
	name  string
	value string
}

type uciSection struct {
	typ  string
	name string
	opts []uciOption
}

func (s *uciSection) option(name, value string) {
	s.opts = append(s.opts, uciOption{name: name, value: value})
}

func (s *uciSection) addList(name, value string) {
	s.opts = append(s.opts, uciOption{list: true, name: name, value: value})
}

// uciConfig is an endpoint's configuration as UCI sections.
type uciConfig struct {
	iface    uciSection
	peers    []uciSection
	peerType string
	// hookComments list the hooks that were not applied (R-UCI-4).
	hookComments []string
}

// uciName returns s with every character other than a letter, digit or _
// replaced by _ (R-UCI-1).
func uciName(s string) string {
	return strings.Map(func(r rune) rune {
		if r == '_' || ('a' <= r && r <= 'z') || ('A' <= r && r <= 'Z') || ('0' <= r && r <= '9') {
			return r
		}
		return '_'
	}, s)
}

// quote single-quotes s so that it is safe in a UCI file and in sh (R-UCI-2).
func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func buildUCI(cfg *network.Config) (*uciConfig, error) {
	e := cfg.Endpoint
	ifName := uciName(cfg.Interface)
	u := &uciConfig{peerType: "wireguard_" + ifName}

	u.iface = uciSection{typ: "interface", name: ifName}
	u.iface.option("proto", "wireguard")
	u.iface.option("private_key", cfg.PrivateKey.String())
	for _, a := range e.Addresses {
		u.iface.addList("addresses", a.String())
	}
	if e.ListenPort != 0 {
		u.iface.option("listen_port", strconv.Itoa(e.ListenPort))
	}
	if e.MTU != 0 {
		u.iface.option("mtu", strconv.Itoa(e.MTU))
	}
	for _, d := range e.DNS {
		u.iface.addList("dns", d)
	}

	for _, h := range hooks(e) {
		for _, c := range h.cmds {
			u.hookComments = append(u.hookComments, fmt.Sprintf("%s = %s", h.key, c))
		}
	}

	sections := map[string]string{ifName: "interface " + cfg.Interface}
	for _, p := range cfg.Peers {
		s := uciSection{typ: u.peerType, name: uciName(cfg.Interface + "_" + p.Name)}
		if other, dup := sections[s.name]; dup {
			return nil, fmt.Errorf("endpoint %q: peer %q and %s both map to UCI section %q", e.Name, p.Name, other, s.name)
		}
		sections[s.name] = fmt.Sprintf("peer %q", p.Name)

		s.option("description", p.Name) // R-UCI-3
		s.option("public_key", p.PublicKey.String())
		if p.PresharedKey != nil {
			s.option("preshared_key", p.PresharedKey.String())
		}
		if p.Host != "" {
			s.option("endpoint_host", p.Host)
			s.option("endpoint_port", strconv.Itoa(p.Port))
		}
		for _, ip := range p.AllowedIPs {
			s.addList("allowed_ips", ip.String())
		}
		s.option("route_allowed_ips", "1") // R-UCI-3
		if p.PersistentKeepalive != 0 {
			s.option("persistent_keepalive", strconv.Itoa(p.PersistentKeepalive))
		}
		u.peers = append(u.peers, s)
	}
	return u, nil
}

// renderUCI writes an /etc/config/network fragment.
func renderUCI(b *bytes.Buffer, cfg *network.Config) error {
	u, err := buildUCI(cfg)
	if err != nil {
		return err
	}

	// R-OUT-1
	fmt.Fprintf(b, "# OpenWRT network configuration for endpoint %q, generated by kwikmesh.\n", cfg.Endpoint.Name)
	fmt.Fprintf(b, "# Install it by replacing the %s interface and its %s peers in\n", quote(u.iface.name), u.peerType)
	b.WriteString("# /etc/config/network with it, then run: /etc/init.d/network reload\n")

	writeUCISection(b, &u.iface)
	writeHookComments(b, u.hookComments)
	for i := range u.peers {
		writeUCISection(b, &u.peers[i])
	}
	return nil
}

func writeUCISection(b *bytes.Buffer, s *uciSection) {
	fmt.Fprintf(b, "\nconfig %s %s\n", s.typ, quote(s.name))
	for _, o := range s.opts {
		kind := "option"
		if o.list {
			kind = "list"
		}
		fmt.Fprintf(b, "\t%s %s %s\n", kind, o.name, quote(o.value))
	}
}

// writeHookComments lists the hooks that were not applied (R-HOOK-4,
// R-UCI-4).
func writeHookComments(b *bytes.Buffer, comments []string) {
	if len(comments) == 0 {
		return
	}
	b.WriteString("\n# OpenWRT does not support wg-quick hooks; these were not applied:\n")
	for _, c := range comments {
		fmt.Fprintf(b, "#   %s\n", c)
	}
}

// renderUCIScript writes a shell script of uci commands that replaces the
// interface and all of its peers (R-UCI-5).
func renderUCIScript(b *bytes.Buffer, cfg *network.Config) error {
	u, err := buildUCI(cfg)
	if err != nil {
		return err
	}

	// R-OUT-1
	b.WriteString("#!/bin/sh\n")
	fmt.Fprintf(b, "# OpenWRT network setup script for endpoint %q, generated by kwikmesh.\n", cfg.Endpoint.Name)
	fmt.Fprintf(b, "# Copy it to the router and run it there as root: sh %s.sh\n", cfg.Endpoint.Name)
	b.WriteString("set -e\n")

	b.WriteString("\n# Remove the existing interface and all of its peers.\n")
	fmt.Fprintf(b, "uci -q delete %s || true\n", quote("network."+u.iface.name))
	fmt.Fprintf(b, "while uci -q delete %s; do :; done\n", quote("network.@"+u.peerType+"[0]"))

	b.WriteString("\n# Interface\n")
	writeUCICommands(b, &u.iface)
	writeHookComments(b, u.hookComments)
	for i := range u.peers {
		fmt.Fprintf(b, "\n# Peer %s\n", cfg.Peers[i].Name)
		writeUCICommands(b, &u.peers[i])
	}

	b.WriteString("\nuci commit network\n")
	b.WriteString("/etc/init.d/network reload\n")
	return nil
}

func writeUCICommands(b *bytes.Buffer, s *uciSection) {
	fmt.Fprintf(b, "uci set network.%s=%s\n", s.name, quote(s.typ))
	for _, o := range s.opts {
		cmd := "set"
		if o.list {
			cmd = "add_list"
		}
		fmt.Fprintf(b, "uci %s network.%s.%s=%s\n", cmd, s.name, o.name, quote(o.value))
	}
}
