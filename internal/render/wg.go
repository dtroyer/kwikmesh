// internal/render/wg.go - wg-quick output format

package render

import (
	"bytes"
	"fmt"
	"strings"

	"kwikmesh/internal/network"
)

// renderWG writes a wg-quick config (R-WG-1 to R-WG-3).
func renderWG(b *bytes.Buffer, cfg *network.Config) error {
	e := cfg.Endpoint

	// R-OUT-1
	fmt.Fprintf(b, "# WireGuard configuration for endpoint %q, generated by kwikmesh.\n", e.Name)
	fmt.Fprintf(b, "# Install it as /etc/wireguard/%s.conf and bring it up with: wg-quick up %s\n", cfg.Interface, cfg.Interface)

	b.WriteString("\n[Interface]\n")
	fmt.Fprintf(b, "PrivateKey = %s\n", cfg.PrivateKey)
	fmt.Fprintf(b, "Address = %s\n", joinPrefixes(e.Addresses, ", "))
	if e.ListenPort != 0 {
		fmt.Fprintf(b, "ListenPort = %d\n", e.ListenPort)
	}
	if e.MTU != 0 {
		fmt.Fprintf(b, "MTU = %d\n", e.MTU)
	}
	if len(e.DNS) > 0 {
		fmt.Fprintf(b, "DNS = %s\n", strings.Join(e.DNS, ", "))
	}
	for _, h := range hooks(e) {
		for _, c := range h.cmds {
			fmt.Fprintf(b, "%s = %s\n", h.key, c) // R-HOOK-3
		}
	}

	for _, p := range cfg.Peers {
		b.WriteString("\n[Peer]\n")
		fmt.Fprintf(b, "# %s\n", p.Name)
		if d := strings.Join(strings.Fields(p.Description), " "); d != "" {
			fmt.Fprintf(b, "# %s\n", d)
		}
		fmt.Fprintf(b, "PublicKey = %s\n", p.PublicKey)
		if p.PresharedKey != nil {
			fmt.Fprintf(b, "PresharedKey = %s\n", p.PresharedKey)
		}
		if p.Host != "" {
			fmt.Fprintf(b, "Endpoint = %s\n", p.Endpoint())
		}
		if len(p.AllowedIPs) > 0 {
			fmt.Fprintf(b, "AllowedIPs = %s\n", joinPrefixes(p.AllowedIPs, ", "))
		}
		if p.PersistentKeepalive != 0 {
			fmt.Fprintf(b, "PersistentKeepalive = %d\n", p.PersistentKeepalive)
		}
	}
	return nil
}
