// R-CLI-5, R-SEC-1, R-SEC-2
func TestGenerateOutput(t *testing.T) {
	cfg := writeNetwork(t, false)
	dir := t.TempDir()

	conf := filepath.Join(dir, "laptop.conf")
	// An existing file is replaced, and does not keep its looser mode.
	if err := os.WriteFile(conf, []byte("old"), 0o644); err != nil {
		t.Fatal(err)
	}
	if out := mustRun(t, "-c", cfg, "gen", "laptop", "-o", conf); out != "" {
		t.Errorf("unexpected stdout: %q", out)
	}
	want := mustRun(t, "-c", cfg, "gen", "laptop")
	if got, _ := os.ReadFile(conf); string(got) != want {
		t.Errorf("file contents:\n%s\nwant:\n%s", got, want)
	}
	if m := fileMode(t, conf); m != 0o600 {
		t.Errorf("mode = %o, want 600", m)
	}

	script := filepath.Join(dir, "router.sh")
	mustRun(t, "-c", cfg, "gen", "router", "--output", script)
	if m := fileMode(t, script); m != 0o700 {
		t.Errorf("script mode = %o, want 700", m)
	}

	// No temporary files are left behind.
	entries, _ := os.ReadDir(dir)
	if len(entries) != 2 {
		t.Errorf("directory has %d entries, want 2", len(entries))
	}

	// A failed build leaves no file.
	failed := filepath.Join(dir, "phone.conf")
	runErr(t, "-c", cfg, "gen", "phone", "-o", failed)
	if _, err := os.Stat(failed); !os.IsNotExist(err) {
		t.Errorf("phone.conf exists after a failure: %v", err)
	}
}

// R-CLI-6, R-CLI-7, R-SEC-1
func TestGenerateAll(t *testing.T) {
	cfg := writeNetwork(t, true)
	dir := filepath.Join(t.TempDir(), "out", "sub")

	out := mustRun(t, "-c", cfg, "gen", "--all", "--dir", dir, "-f", "wg,uci", "-f", "uci-script")
	var want []string
	for _, name := range []string{"router", "laptop", "phone"} {
		for _, ext := range []string{".conf", ".uci", ".sh"} {
			want = append(want, "wrote "+filepath.Join(dir, name+ext))
		}
	}
	if got := strings.Split(strings.TrimSuffix(out, "\n"), "\n"); !slices.Equal(got, want) {
		t.Errorf("output:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}

	if m := fileMode(t, dir); m != 0o700 {
		t.Errorf("directory mode = %o, want 700", m)
	}
	for _, f := range []struct {
		name string
		mode os.FileMode
	}{{"laptop.conf", 0o600}, {"laptop.uci", 0o600}, {"laptop.sh", 0o700}} {
		if m := fileMode(t, filepath.Join(dir, f.name)); m != f.mode {
			t.Errorf("%s: mode = %o, want %o", f.name, m, f.mode)
		}
	}
	wantConf := mustRun(t, "-c", cfg, "gen", "laptop")
	if got, _ := os.ReadFile(filepath.Join(dir, "laptop.conf")); string(got) != wantConf {
		t.Errorf("laptop.conf differs from generate laptop")
	}
}

