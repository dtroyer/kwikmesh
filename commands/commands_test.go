// R-CLI-9: a failure for one endpoint doesn't stop the others, and every
// failure is reported at the end.
func TestGenerateAllPartialFailure(t *testing.T) {
	cfg := writeConfig(t, `
endpoints:
  - name: badfile
    addresses: [10.0.0.1]
    public_key: `+key(1).PublicKey().String()+`
    private_key_file: bad.key
  - name: a
    addresses: [10.0.0.2]
    private_key: `+key(2).String()+`
  - name: wrongfile
    addresses: [10.0.0.3]
    public_key: `+key(3).PublicKey().String()+`
    private_key_file: good.key
`)
	keyDir := filepath.Dir(cfg)
	if err := os.WriteFile(filepath.Join(keyDir, "bad.key"), []byte("junk\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(keyDir, "good.key"), []byte(key(4).String()+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	dir := t.TempDir()
	stdout, stderr, err := run(t, "-c", cfg, "gen", "-a", "-d", dir)
	if err == nil {
		t.Fatal("expected an error")
	}
	if want := "wrote " + filepath.Join(dir, "a.conf") + "\n"; stdout != want {
		t.Errorf("stdout:\n%s\nwant:\n%s", stdout, want)
	}
	lines := strings.Split(strings.TrimSuffix(stderr, "\n"), "\n")
	if len(lines) != 2 ||
		!strings.HasPrefix(lines[0], `km: endpoint "badfile": private_key_file `) || !strings.Contains(lines[0], "bad.key: must be a base64-encoded 32-byte key") ||
		!strings.HasPrefix(lines[1], `km: endpoint "wrongfile": private_key_file `) || !strings.HasSuffix(lines[1], "does not match public_key") {
		t.Errorf("stderr:\n%s", stderr)
	}
}

// R-CLI-5, R-CLI-8
func TestGenerateUsageErrors(t *testing.T) {
	cfg := writeNetwork(t, true)
	for _, tt := range []struct {
		args []string
		want string
	}{
		{[]string{"gen"}, "km: generate: missing endpoint name\n"},
		{[]string{"gen", "router", "laptop"}, "km: generate: takes one endpoint name, got 2\n"},
		{[]string{"gen", "router", "-f", "wg", "-f", "uci"}, "km: only one --format is allowed without --all\n"},
		{[]string{"gen", "router", "-f", "wg,uci"}, "km: only one --format is allowed without --all\n"},
		{[]string{"gen", "router", "-f", "ini"}, "km: unknown format \"ini\" (want wg, uci, uci-script)\n"},
		{[]string{"gen", "router", "-d", "x"}, "km: --dir is only valid with --all\n"},
		{[]string{"gen", "-a", "router", "-d", "x"}, "km: --all cannot be combined with an endpoint name\n"},
		{[]string{"gen", "-a", "-o", "x", "-d", "x"}, "km: --all cannot be combined with --output\n"},
		{[]string{"gen", "-a"}, "km: --all requires --dir\n"},
		{[]string{"gen", "nobody"}, "km: unknown endpoint \"nobody\"\n"},
		{[]string{"gen", "router", "-i", "no/slash"}, "km: invalid interface name \"no/slash\": use up to 15 letters, digits and _=+.-\n"},
	} {
		if got := runErr(t, append([]string{"-c", cfg}, tt.args...)...); got != tt.want {
			t.Errorf("km %s: stderr = %q, want %q", strings.Join(tt.args, " "), got, tt.want)
		}
	}
}

