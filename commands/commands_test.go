func key(b byte) network.Key {
	var k network.Key
	for i := range k {
		k[i] = b
	}
	return k
}

// testNetwork is a network file in which phone has only a public key, so
// its configuration cannot be generated. {phone-key} is replaced by the
// caller.
const testNetwork = `
defaults:
  listen_port: 51820
endpoints:
  - name: router
    format: uci-script
    addresses: [10.0.0.1/24]
    endpoint: vpn.example.com
    private_key: {key1}
  - name: laptop
    addresses: [10.0.0.2]
    private_key: {key2}
  - name: phone
    addresses: [10.0.0.3]
    {phone-key}
    peers: [router]
`

// writeNetwork writes a network file into a new directory and returns its
// path. If phonePrivate is set, phone has a private key.
func writeNetwork(t *testing.T, phonePrivate bool) string {
	t.Helper()
	phone := "public_key: " + key(3).PublicKey().String()
	if phonePrivate {
		phone = "private_key: " + key(3).String()
	}
	config := strings.NewReplacer(
		"{key1}", key(1).String(),
		"{key2}", key(2).String(),
		"{phone-key}", phone,
	).Replace(testNetwork)
	return writeConfig(t, config)
}

func writeConfig(t *testing.T, config string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "config.yaml")
	if err := os.WriteFile(path, []byte(config), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func mustRun(t *testing.T, args ...string) string {
	t.Helper()
	stdout, stderr, err := run(t, args...)
	if err != nil {
		t.Fatalf("km %s: %v\n%s", strings.Join(args, " "), err, stderr)
	}
	if stderr != "" {
		t.Errorf("km %s: unexpected stderr: %s", strings.Join(args, " "), stderr)
	}
	return stdout
}

// runErr runs km, which must fail, and returns stderr.
func runErr(t *testing.T, args ...string) string {
	t.Helper()
	_, stderr, err := run(t, args...)
	if err == nil {
		t.Fatalf("km %s succeeded, want an error", strings.Join(args, " "))
	}
	return stderr
}

func fileMode(t *testing.T, path string) os.FileMode {
	t.Helper()
	fi, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	return fi.Mode().Perm()
}

// R-CLI-5, R-FMT-2, R-CLI-2, R-CLI-3
func TestGenerate(t *testing.T) {
	cfg := writeNetwork(t, false)

	out := mustRun(t, "-c", cfg, "generate", "laptop")
	for _, want := range []string{
		`# WireGuard configuration for endpoint "laptop", generated by kwikmesh.`,
		"PrivateKey = " + key(2).String(),
		"# router\nPublicKey = " + key(1).PublicKey().String(),
		"Endpoint = vpn.example.com:51820",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("output missing %q:\n%s", want, out)
		}
	}

	// The alias, and options after the command and the endpoint name.
	for _, args := range [][]string{
		{"gen", "laptop", "-c", cfg},
		{"generate", "--config", cfg, "laptop"},
		{"gen", "laptop", "--config=" + cfg},
	} {
		if got := mustRun(t, args...); got != out {
			t.Errorf("km %s output differs:\n%s", strings.Join(args, " "), got)
		}
	}

	// router is in its own format.
	if out := mustRun(t, "-c", cfg, "gen", "router"); !strings.HasPrefix(out, "#!/bin/sh\n") {
		t.Errorf("router is not a uci-script:\n%s", out)
	}
}

