// R-FILE-1: --config, then KWIKMESH_CONFIG, then config.yaml.
func TestConfigSelection(t *testing.T) {
	flagCfg := writeNetwork(t, false)
	envCfg := writeNetwork(t, false)

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "config.yaml"), []byte(testNetwork), 0o600); err != nil {
		t.Fatal(err)
	}
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(wd) })

	// Unset, and set but empty. t.Setenv restores the variable afterwards.
	t.Setenv("KWIKMESH_CONFIG", "")
	if err := os.Unsetenv("KWIKMESH_CONFIG"); err != nil {
		t.Fatal(err)
	}
	if got := runErr(t, "validate"); !strings.HasPrefix(got, "km: config.yaml: ") {
		t.Errorf("unset: stderr = %q, want config.yaml", got)
	}
	t.Setenv("KWIKMESH_CONFIG", "")
	if got := runErr(t, "validate"); !strings.HasPrefix(got, "km: config.yaml: ") {
		t.Errorf("empty: stderr = %q, want config.yaml", got)
	}

	t.Setenv("KWIKMESH_CONFIG", envCfg)
	if got := mustRun(t, "validate"); got != envCfg+": OK\n" {
		t.Errorf("env: output = %q", got)
	}
	if got := mustRun(t, "validate", "-c", flagCfg); got != flagCfg+": OK\n" {
		t.Errorf("flag: output = %q", got)
	}
}

// R-CLI-12
func TestGenkeyGenpsk(t *testing.T) {
	seen := map[string]bool{}
	for _, cmd := range []string{"genkey", "genkey", "genpsk", "genpsk"} {
		out := mustRun(t, cmd)
		s, ok := strings.CutSuffix(out, "\n")
		k, err := network.ParseKey(s)
		if !ok || err != nil {
			t.Fatalf("%s: output %q is not a key and a newline", cmd, out)
		}
		if seen[s] {
			t.Errorf("%s: repeated key %s", cmd, s)
		}
		seen[s] = true
		if cmd == "genkey" && (k[0]&7 != 0 || k[31]&128 != 0 || k[31]&64 == 0) {
			t.Errorf("genkey: %s is not clamped", s)
		}
	}
	if got := runErr(t, "genpsk", "x"); got != "km: genpsk: unexpected argument \"x\"\n" {
		t.Errorf("stderr = %q", got)
	}
}

